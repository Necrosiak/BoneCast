const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/deferredView.ts'), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const timers = new Map();
let sequence = 0, openings = 0;
const context = { exports: {}, setTimeout: fn => { timers.set(++sequence, fn); return sequence; }, clearTimeout: id => timers.delete(id) };
vm.createContext(context);
vm.runInContext(code, context);
const view = context.exports.deferredView(() => openings++);
view.schedule(); view.schedule();
assert.equal(timers.size, 1, 'repeated route effects schedule one opening');
let fire = [...timers.values()][0]; timers.clear(); fire();
assert.equal(openings, 1);
view.schedule(); view.cancel();
assert.equal(timers.size, 0, 'unloading the plugin cancels a pending opening');
assert.equal(openings, 1);
view.schedule(); fire = [...timers.values()][0]; timers.clear(); fire();
assert.equal(openings, 2, 'the view can be opened again after cancellation');
console.log('PASS deferred view: duplicate opening, unload cancellation, reopening');
